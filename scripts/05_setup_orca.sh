#!/usr/bin/env bash
# Wire the local Qwen + pi stack into orca (github.com/orca-cli/orca),
# the orchestration layer that runs coding agents in isolated git worktrees.
#
# Two directions:
#   (A) pi drives orca     : orca is registered as an MCP server in pi (verified in orca README)
#   (B) orca launches pi   : orca's adapters start an agent CLI per run. Set pi as the agent
#                            command in your repo's .orca/orca.toml (field names depend on your
#                            installed orca version — see `orca --help` / DOCS.md).
source "$(dirname "$0")/common.sh"

have pi || fail "pi 가 없습니다."

if ! have orca; then
  [[ "$OFFLINE" == "1" ]] && fail "오프라인 모드: 번들에 orca 가 없습니다. make_bundle.sh 를 orca 또는 go 가 있는 머신에서 다시 만드세요."
  info "orca 설치 (brew install orca-cli/tap/orca)"
  brew install orca-cli/tap/orca
fi
info "orca $(orca version 2>/dev/null || orca --version 2>/dev/null || echo '?')"

# (A) register orca as an MCP server in pi (user-level)
info "pi MCP 등록: orca (orca mcp serve)"
merge_json "$PI_AGENT_DIR/mcp.json" '{
  "mcpServers": {
    "orca": { "command": "orca", "args": ["mcp", "serve"] }
  }
}'

# (B) a wrapper so orca (or anything else) can launch pi non-interactively on the local model.
#     Usage: pi-local "<prompt>"      -> runs in the current worktree, prints result, exits
wrapper="$HOME/.local/bin/pi-local"
mkdir -p "$(dirname "$wrapper")"
cat > "$wrapper" <<EOF
#!/usr/bin/env bash
# Non-interactive pi on the local Qwen3-Coder-Next model. Generated by 05_setup_orca.sh.
export PI_OFFLINE=1 PI_SKIP_VERSION_CHECK=1
exec pi --model "local/$MODEL_ID" -p "\$@"
EOF
chmod +x "$wrapper"
info "래퍼 생성: $wrapper  (예: pi-local \"Add unit tests for utils.py\")"

cat <<'EOF'

orca 쪽 설정 (repo 루트에서):
  orca init                               # .orca/ 생성 (버전에 따라 명령이 다를 수 있음)
  cp templates/orca/AGENTS.md .orca/      # 모든 run 에 주입되는 지침 (로컬 모델용으로 짧게 유지)

.orca/orca.toml 의 기본 adapter 를 pi 로 잡을 때는 `orca --help` 로 adapter 목록/필드명을 확인한 뒤
agent 실행 커맨드를  ~/.local/bin/pi-local  로 지정하세요. orca 가 custom command adapter 를
지원하지 않는 버전이면 (A) 방식만 사용합니다: pi 세션 안에서 orca 의 run/pod 도구를 호출해
워크트리 생성·상태 추적을 맡기고, 코딩은 pi + Qwen 이 그대로 수행합니다.

확인:  pi mcp list   →  blender, orca (, orcaslicer) 가 보여야 합니다.
EOF
info "다음: ./scripts/check.sh  (OrcaSlicer 도 쓰면 07_setup_orcaslicer_mcp.sh)"
