#!/usr/bin/env bash
# Wire the local Qwen + pi stack into Orca. Two different products share the name:
#
#   (1) Orca desktop app (onorca.dev, stablyai/orca)  — agent workspace manager with native Pi support.
#       CLI has `agent launch`, `worktree create`, `agent-context`. pi is launched BY Orca as an agent.
#   (2) orca-cli/orca (Go orchestrator)                — exposes `orca mcp serve`; pi drives it over MCP.
#
# This script detects which one is installed and configures accordingly. Safe to re-run.
source "$(dirname "$0")/common.sh"
have pi || fail "pi 가 없습니다."

if ! have orca; then
  [[ "$OFFLINE" == "1" ]] && fail "오프라인 모드: orca 바이너리가 없습니다 (update.tgz 에 포함되게 온라인 Mac 에서 make_update.sh 를 다시 실행)."
  info "orca-cli/orca 설치 (brew install orca-cli/tap/orca)"
  brew install orca-cli/tap/orca
fi
ORCA_HELP="$(orca --help 2>&1 || true)"

# non-interactive pi wrapper (useful for both flavours and for scripts/automations)
wrapper="$HOME/.local/bin/pi-local"; mkdir -p "$(dirname "$wrapper")"
cat > "$wrapper" <<EOF
#!/usr/bin/env bash
# Non-interactive pi on the local Qwen3-Coder-Next model. Generated by 05_setup_orca.sh.
export PI_OFFLINE=1 PI_SKIP_VERSION_CHECK=1
exec pi --model "local/$MODEL_ID" -p "\$@"
EOF
chmod +x "$wrapper"

remove_orca_mcp_entry() {
  [[ -f "$PI_AGENT_DIR/mcp.json" ]] || return 0
  python3 - "$PI_AGENT_DIR/mcp.json" <<'PY'
import json,sys,pathlib
p=pathlib.Path(sys.argv[1]); d=json.loads(p.read_text() or "{}")
s=d.get("mcpServers",{})
if s.get("orca",{}).get("command")=="orca" and s["orca"].get("args")==["mcp","serve"]:
    del s["orca"]; p.write_text(json.dumps(d,indent=2,ensure_ascii=False)+"\n"); print("  removed stale mcp.json entry: orca (no `orca mcp serve` in this build)")
PY
}

if grep -qE '^\s+agent launch|agent-context' <<<"$ORCA_HELP"; then
  # ---------------- (1) Orca desktop app ----------------
  info "Orca 데스크톱 앱 감지 ($(orca --version 2>/dev/null | head -1)). Pi 를 Orca 의 에이전트로 사용합니다."
  remove_orca_mcp_entry
  cat <<EOF

Orca 앱에서 한 번만 설정:
  Settings → Agents → Pi 활성화
    Command   : $(command -v pi)        (자동 감지되면 그대로)
    Arguments : --model local/$MODEL_ID  (pi 에서 /model → Ctrl+S 로 기본 모델을 저장했다면 비워도 됨)
  Settings → Agents → Agent status hooks : 켜두면 Orca UI 에 working/waiting/done 상태 표시

CLI 예:
  orca worktree create --name my-task --agent pi --prompt "작업 설명"
  orca agent launch --agent pi --model local/$MODEL_ID --worktree <selector>

pi 가 worktree 안에서 실행되므로 ~/.pi/agent 의 models.json / mcp.json / skills / AGENTS.md 가 그대로 적용됩니다.
모델 서버는 미리 띄워 두세요:  qwen start
EOF
elif grep -qE '^\s+mcp\b' <<<"$ORCA_HELP" || orca mcp --help >/dev/null 2>&1; then
  # ---------------- (2) orca-cli/orca ----------------
  info "orca-cli/orca 감지. pi 에 MCP 서버로 등록합니다 (orca mcp serve)."
  merge_json "$PI_AGENT_DIR/mcp.json" '{"mcpServers":{"orca":{"command":"orca","args":["mcp","serve"]}}}'
  cat <<'EOF'

repo 에서:  orca init  →  cp templates/orca/AGENTS.md .orca/  →  pi 안에서 orca 도구로 run/worktree 관리
확인:       pi mcp list
EOF
else
  remove_orca_mcp_entry
  warn "알 수 없는 orca 빌드입니다. 'orca --help' 출력을 확인하세요. (pi-local 래퍼만 생성함)"
fi
info "래퍼: $wrapper  (예: pi-local \"Add unit tests for utils.py\")"
