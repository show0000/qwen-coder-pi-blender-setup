#!/usr/bin/env bash
# Install everything from a bundle made by make_bundle.sh — no network required.
#
#   install_offline.sh <bundle-dir> [model-src-dir]
#     model-src-dir : folder containing the GGUF (or MLX) weights, e.g. /Volumes/USB/Qwen3-Coder-Next-GGUF
#                     (omit if the bundle was built with --with-model or you'll copy weights yourself)
#
# Installs under ~/.local (no sudo, no Homebrew):
#   ~/.local/opt/{node,pi,llama.cpp}   ~/.local/bin/{pi,node,npm,uv,uvx,jq,orca,llama-server,...}
#   ~/.local/share/uv/python           ~/.local/bin/<mcp entry points> (uv tool, offline wheelhouse)
set -euo pipefail
B="${1:?usage: install_offline.sh <bundle-dir> [model-src-dir]}"; B="$(cd "$B" && pwd)"
MODEL_SRC="${2:-}"
[[ -f "$B/manifest.env" ]] || { echo "manifest.env 가 없습니다. make_bundle.sh 로 만든 폴더인지 확인하세요." >&2; exit 1; }
# shellcheck disable=SC1091
source "$B/manifest.env"

export OFFLINE=1
REPO="$B/repo"
source "$REPO/scripts/common.sh"
require_macos_arm
xcode-select -p >/dev/null 2>&1 || warn "Xcode Command Line Tools 가 없습니다 (git 필요). 'xcode-select --install' 은 오프라인에서 불가하니 설치 패키지를 따로 준비하세요."

OPT="$HOME/.local/opt"; BIN="$HOME/.local/bin"
mkdir -p "$OPT" "$BIN" "$HOME/.local/share/uv" "$HOME/.local/state/qwen-coder"
unq() { xattr -dr com.apple.quarantine "$@" 2>/dev/null || true; }

# ---- node + pi ---------------------------------------------------------------
info "Node $NODE_VERSION"
rm -rf "$OPT/node"; mkdir -p "$OPT/node"; tar -xzf "$B/node/$NODE_TGZ" -C "$OPT/node" --strip-components 1
ln -sf "$OPT/node/bin/node" "$BIN/node"; ln -sf "$OPT/node/bin/npm" "$BIN/npm"; ln -sf "$OPT/node/bin/npx" "$BIN/npx"
info "pi $PI_VERSION"
rm -rf "$OPT/pi"; mkdir -p "$OPT/pi"; tar -xzf "$B/pi/pi-prefix.tgz" -C "$OPT/pi" --strip-components 1
# the npm bin shim is a symlink into lib/node_modules; wrap it so PATH to node is guaranteed
cat > "$BIN/pi" <<EOF
#!/usr/bin/env bash
export PATH="$OPT/node/bin:\$PATH"
export PI_OFFLINE=1 PI_SKIP_VERSION_CHECK=1 PI_TELEMETRY=0
exec "$OPT/pi/bin/pi" "\$@"
EOF
chmod +x "$BIN/pi"; unq "$OPT/node" "$OPT/pi"

# ---- uv + python + wheels ----------------------------------------------------
info "uv / Python $PY_VERSION"
cp "$B/bin/uv" "$B/bin/uvx" "$BIN/"; chmod +x "$BIN/uv" "$BIN/uvx"; unq "$BIN/uv" "$BIN/uvx"
if [[ -f "$B/python.tgz" ]]; then
  tar -xzf "$B/python.tgz" -C "$HOME/.local/share/uv"          # extracts python/ (symlinks restored)
else
  cp -R "$B/python/." "$HOME/.local/share/uv/python/"           # older bundles: plain directory
fi
unq "$HOME/.local/share/uv/python"
export UV_PYTHON_DOWNLOADS=never UV_OFFLINE=1 UV_NO_INDEX=1 UV_FIND_LINKS="$B/wheels"
PYV=$("$BIN/uv" python find "$PY_VERSION")
info "MCP 서버 설치 (uv tool, wheelhouse)"
"$BIN/uv" tool install -q --python "$PYV" --reinstall mcp-for-blender
"$BIN/uv" tool install -q --python "$PYV" --reinstall orcaslicer-mcp
"$BIN/uv" tool install -q --python "$PYV" --reinstall "huggingface_hub[cli,hf_xet]" || warn "hf CLI 설치 생략"
[[ "${WITH_MLX:-0}" == "1" ]] && "$BIN/uv" tool install -q --python "$PYV" --reinstall mlx-lm
BLENDER_MCP_CMD="$BIN/$BLENDER_EP"; ORCASLICER_MCP_CMD="$BIN/$ORCASLICER_EP"
[[ -x "$BLENDER_MCP_CMD" ]] || fail "blender MCP 엔트리포인트가 없습니다: $BLENDER_MCP_CMD"

# ---- llama.cpp ---------------------------------------------------------------
info "llama.cpp $LLAMA_TAG"
rm -rf "$OPT/llama.cpp"; mkdir -p "$OPT/llama.cpp"; tar -xzf "$B/llama/$LLAMA_TGZ" -C "$OPT/llama.cpp"
# archives contain either build/bin/* or a flat dir; find llama-server
LS=$(find "$OPT/llama.cpp" -type f -name llama-server | head -1); [[ -n "$LS" ]] || fail "llama-server 를 아카이브에서 찾지 못했습니다."
unq "$OPT/llama.cpp"
cat > "$BIN/llama-server" <<EOF
#!/usr/bin/env bash
export DYLD_LIBRARY_PATH="$(dirname "$LS"):\${DYLD_LIBRARY_PATH:-}"
exec "$LS" "\$@"
EOF
chmod +x "$BIN/llama-server"

# ---- jq, orca ----------------------------------------------------------------
cp "$B/bin/jq" "$BIN/jq"; chmod +x "$BIN/jq"; unq "$BIN/jq"
if [[ -f "$B/bin/orca" ]]; then cp "$B/bin/orca" "$BIN/orca"; chmod +x "$BIN/orca"; unq "$BIN/orca"; else warn "번들에 orca 없음 (선택)"; fi

# ---- persistent env ------------------------------------------------------------
ENVF="$HOME/.config/qwen-coder/env.sh"; mkdir -p "$(dirname "$ENVF")"
cat > "$ENVF" <<EOF
# generated by install_offline.sh
export PATH="\$HOME/.local/bin:\$PATH"
export OFFLINE=1 PI_OFFLINE=1 PI_SKIP_VERSION_CHECK=1 PI_TELEMETRY=0
export UV_PYTHON_DOWNLOADS=never UV_OFFLINE=1
export BLENDER_MCP_CMD="$BLENDER_MCP_CMD" ORCASLICER_MCP_CMD="$ORCASLICER_MCP_CMD"
export HF_REPO="$HF_REPO" QUANT="$QUANT"
EOF
for rc in "$HOME/.zprofile" "$HOME/.zshrc"; do
  grep -qs 'qwen-coder/env.sh' "$rc" || printf '\n[ -f "%s" ] && source "%s"\n' "$ENVF" "$ENVF" >> "$rc"
done
# shellcheck disable=SC1090
source "$ENVF"; export BLENDER_MCP_CMD ORCASLICER_MCP_CMD

# ---- model weights -------------------------------------------------------------
if [[ -z "$MODEL_SRC" && -d "$B/models/$HF_REPO" ]]; then MODEL_SRC="$B/models/$HF_REPO"; fi
if [[ -n "$MODEL_SRC" ]]; then
  info "모델 복사: $MODEL_SRC → $MODEL_DIR  (수십 GB, 시간이 걸립니다)"
  mkdir -p "$MODEL_DIR"
  if command -v rsync >/dev/null 2>&1; then
    rsync -ah --progress "$MODEL_SRC/" "$MODEL_DIR/"
  elif [[ "$MODEL_SRC" == *:* ]]; then
    fail "rsync 가 없어 원격 경로를 복사할 수 없습니다. 온라인 Mac 에서 'python3 -m http.server' 를 띄우고 curl -C - 로 $MODEL_DIR 에 직접 받으세요 (docs/OFFLINE.md)."
  else
    cp -v "$MODEL_SRC"/*.gguf "$MODEL_DIR/" 2>/dev/null || cp -Rv "$MODEL_SRC"/. "$MODEL_DIR/"
  fi
else
  warn "모델 소스가 지정되지 않았습니다. 나중에 가중치를 $MODEL_DIR 에 넣으세요."
fi

# ---- pi / MCP registration (reuse the normal scripts) -------------------------
"$REPO/scripts/03_setup_pi.sh"
"$REPO/scripts/04_setup_blender_mcp.sh"
command -v orca >/dev/null 2>&1 && "$REPO/scripts/05_setup_orca.sh" || true

cat <<EOF

설치 완료. 새 터미널을 열거나  source $ENVF  한 뒤:
  $REPO/scripts/02_serve_model.sh --bg     # 모델 서버
  $REPO/scripts/check.sh                   # 점검
  cd ~/your-project && pi --model local/$MODEL_ID
OrcaSlicer 를 쓰면:  ORCA_API_TOKEN=... $REPO/scripts/07_setup_orcaslicer_mcp.sh
EOF
